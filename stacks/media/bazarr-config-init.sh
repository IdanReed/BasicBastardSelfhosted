#!/bin/sh
# bazarr-config-init — seeds config/config.yaml before bazarr starts, so the
# Radarr/Sonarr connections exist without a first-login UI pass. Runs in
# python:3.13-alpine as a oneshot.
#
# WHICH FILE (this settles the annex §6 open question): bazarr/app/config.py
# builds Dynaconf over <config_dir>/config/config.yaml — note the DOUBLED
# `config` — with config.ini treated as legacy and migrated once. Dynaconf +
# a full validator list means a PARTIAL file is correct: every absent key is
# filled from its validator default at boot and the whole document written
# back.
#
# WHY NOT THE API: Bazarr authenticates with X-API-KEY against
# settings.auth.apikey, which on a virgin install is a random 16 bytes nobody
# knows. Pinning it here is what makes the API reachable at all afterwards.
#
# Seed-if-absent, NOT merge: Bazarr rewrites this file on every settings save,
# so a merge on each deploy would revert UI changes. To re-seed, delete
# /mnt/fast/bazarr/config/config/config.yaml.
#
# NOT DONE HERE: System.configured is a DATABASE column, not a settings key,
# so the web UI still shows its first-run wizard once. That flag only drives a
# frontend redirect; the arr connections below work regardless.
set -eu

exec python3 -u - <<'PY'
import os
import sys

OUT_DIR = "/config/config"
OUT = os.path.join(OUT_DIR, "config.yaml")

required = ("BAZARR_API_KEY", "RADARR__AUTH__APIKEY", "SONARR__AUTH__APIKEY")
missing = [k for k in required if not os.environ.get(k)]
if missing:
    sys.exit(f"bazarr-config-init: FATAL: unset or empty in .env: "
             f"{', '.join(missing)} (decrypt race?)")

if os.path.exists(OUT):
    print("bazarr-config-init: config.yaml exists - bazarr owns it, not "
          "touching", flush=True)
    sys.exit(0)


def scalar(value):
    """A single-quoted YAML scalar with doubled quotes. Sufficient for hex API
    keys and hostnames, and it keeps this script dependency-free — there is no
    PyYAML in python:3-alpine."""
    return "'" + str(value).replace("'", "''") + "'"


doc = f"""# GENERATED by bazarr-config-init from .env on first boot.
# Bazarr owns this file afterwards and rewrites it whole on every settings
# save. To re-seed, delete it and redeploy.
general:
  use_sonarr: true
  use_radarr: true
auth:
  # Pinned from sops: the default is a random 16 bytes, which would leave the
  # API unreachable to anything that had not read this file first.
  apikey: {scalar(os.environ["BAZARR_API_KEY"])}
  # Bazarr's own login stays off: bazarr.svc.idanreed.com is `import
  # protected` in the Caddyfile, so Authentik forward auth is the gate.
  type: null
sonarr:
  ip: {scalar(os.environ.get("SONARR_HOST") or "sonarr")}
  port: {int(os.environ.get("SONARR_PORT") or 8989)}
  base_url: '/'
  ssl: false
  apikey: {scalar(os.environ["SONARR__AUTH__APIKEY"])}
radarr:
  ip: {scalar(os.environ.get("RADARR_HOST") or "radarr")}
  port: {int(os.environ.get("RADARR_PORT") or 7878)}
  base_url: '/'
  ssl: false
  apikey: {scalar(os.environ["RADARR__AUTH__APIKEY"])}
"""

os.makedirs(OUT_DIR, exist_ok=True)
tmp = OUT + ".tmp"
with open(tmp, "w") as fh:
    fh.write(doc)
os.chmod(tmp, 0o600)
os.chown(tmp, 1000, 1000)
os.replace(tmp, OUT)
os.chown(OUT_DIR, 1000, 1000)
print("bazarr-config-init: CHANGE: seeded config/config.yaml "
      "(radarr + sonarr connections)", flush=True)
PY
